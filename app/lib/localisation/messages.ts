const normaliseQuotes=(value:string)=>value.replace(/[‘’]/g,"'").replace(/[“”]/g,'"')
const normalisedMessages=Object.fromEntries(Object.entries(arabicMessages).map(([key,value])=>[normaliseQuotes(key),value]))
export function translateMessage(locale:WebsiteLocale,message:string,values:Record<string,string|number>={}){
 if(locale==='ar'){
  const count=message.match(/^(\d+) (episodes|books|chapters)$/)
  if(count)return arabicMessages[`{count} ${count[2]}`].replace('{count}',new Intl.NumberFormat('ar').format(Number(count[1])))
 }
 const template=locale==='ar'?(arabicMessages[message]??normalisedMessages[normaliseQuotes(message)]??message):message
 return template.replace(/\{(\w+)\}/g,(original,key)=>key in values?String(values[key]):original)
}
