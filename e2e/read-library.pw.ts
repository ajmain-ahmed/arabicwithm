import {test,expect} from '@playwright/test'

for(const width of [320,390,768,1440])test(`Read catalogue heading and complete horizontal row at ${width}`,async({page})=>{
 await page.setViewportSize({width,height:900})
 await page.goto('/books')
 const heading=page.getByRole('heading',{name:'Library',exact:true})
 if(width<900){
  await expect(heading).toBeHidden()
  const search=await page.getByRole('textbox',{name:'Search books'}).boundingBox()
  const nav=await page.locator('#main-navbar').boundingBox()
  expect(search!.y-(nav!.y+nav!.height)).toBeLessThan(48)
 }else await expect(heading).toBeVisible()
 const section=page.getByRole('region',{name:'All Books',exact:true}),row=section.getByRole('group',{name:'Scroll All Books'})
 await expect(section).toBeVisible()
 expect(await page.locator('main section').first().getAttribute('aria-labelledby')).toBe('all-books-title')
 const links=row.getByRole('link')
 await expect(links).toHaveCount(6)
 const hrefs=await links.evaluateAll(nodes=>nodes.map(n=>n.getAttribute('href')))
 expect(new Set(hrefs).size).toBe(6)
 const bounds=await links.evaluateAll(nodes=>nodes.map(n=>{const b=n.getBoundingClientRect();return {x:b.x,y:b.y,width:b.width}}))
 expect(new Set(bounds.map(b=>Math.round(b.y))).size).toBe(1)
 const image=row.locator('img').first()
 expect(await image.evaluate(el=>getComputedStyle(el).objectFit)).toBe('contain')
 expect(await links.first().locator('p').evaluate(el=>getComputedStyle(el).textAlign)).toBe('center')
 if(width<600){
  const rowWidth=await row.evaluate(el=>el.clientWidth)
  expect(Math.abs(bounds[0].width*3+20-rowWidth)).toBeLessThan(2)
  expect(await row.evaluate(el=>el.scrollWidth>el.clientWidth)).toBe(true)
  await row.focus();await row.press('ArrowRight')
  await expect.poll(()=>row.evaluate(el=>el.scrollLeft)).toBeGreaterThan(0)
  await row.evaluate(el=>el.scrollTo({left:el.scrollWidth,behavior:'instant'}))
  await expect(links.last()).toBeInViewport()
  const genre=page.getByRole('region',{name:'Mystery',exact:true})
  await expect(genre).toBeVisible()
  expect(await genre.getByRole('link').first().getAttribute('href')).toBe(hrefs[0])
  await row.hover();await page.mouse.wheel(0,500)
  await expect.poll(()=>page.evaluate(()=>window.scrollY)).toBeGreaterThan(0)
 }else await expect(page.getByRole('region',{name:'Book library',exact:true})).toBeVisible()
 await page.getByRole('textbox',{name:'Search books'}).fill('Book 2')
 await expect(links).toHaveCount(1)
 await page.getByRole('button',{name:'Clear search'}).click();await expect(links).toHaveCount(6)
 expect(await links.evaluateAll(nodes=>nodes.map(n=>n.getAttribute('href')))).toEqual(hrefs)
 await page.getByRole('button',{name:'Listen',exact:true}).click();await expect(section).toHaveCount(0)
 await expect(page.getByRole('region',{name:'Audiobook library',exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Read',exact:true}).click();await expect(links).toHaveCount(6)
 await row.getByRole('link').filter({hasText:'Test Book'}).click()
 await expect(page).toHaveURL('/books/test-book')
})
