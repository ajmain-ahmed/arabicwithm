import {test,expect} from '@playwright/test'
const backend=`https://localhost:${process.env.AWM_TEST_BACKEND_PORT??4310}`
for(const width of [320,390,768,1440])test(`Word Search cleanup at ${width}`,async({page,request})=>{
 await request.post(`${backend}/fixture/word-search`)
 await page.setViewportSize({width,height:1000});await page.goto('/word-search')
 await expect(page.getByRole('heading',{name:'Word Search',exact:true})).toHaveCount(0)
 await expect(page.getByRole('heading',{name:'Choose your difficulty',exact:true})).toBeVisible()
 await page.getByRole('button',{name:/Easy difficulty/}).click()
 await page.getByRole('button',{name:'Start Easy',exact:true}).click()
 const board=page.getByRole('grid')
 await expect(board).toBeVisible()
 await expect(page.getByRole('button',{name:'Hint',exact:true})).toHaveCount(0)
 const status=page.locator('[data-word-search-status]')
 await expect(status.getByRole('button',{name:'Restart game',exact:true})).toBeVisible()
 await expect(status.getByRole('button',{name:'New game',exact:true})).toBeVisible()
 const originalGrid=await board.textContent()
 await status.getByRole('button',{name:'Restart game',exact:true}).click()
 await expect(board).toHaveText(originalGrid!)
 await status.getByRole('button',{name:'New game',exact:true}).click()
 await expect(board).not.toHaveText(originalGrid!)
 const statusBoxes=await status.locator('> *').evaluateAll(nodes=>nodes.map(node=>{const b=node.getBoundingClientRect();return b.y+b.height/2}))
 expect(Math.max(...statusBoxes)-Math.min(...statusBoxes)).toBeLessThan(2)
 const vocab=page.locator('[data-word-search-vocabulary]')
 await expect(vocab).toBeVisible()
 await expect(vocab.getByRole('region')).toHaveCount(0)
 const chips=vocab.getByRole('button')
 expect(await chips.count()).toBeGreaterThan(0)
 const [gridBounds,vocabBounds]=await Promise.all([board.boundingBox(),vocab.boundingBox()])
 expect(vocabBounds!.y).toBeGreaterThan(gridBounds!.y+gridBounds!.height)
 await chips.first().click()
 await expect(vocab.getByRole('region')).toContainText('Meaning')
 await expect(vocab.getByRole('region')).toContainText('Stored fixture example.')
 await chips.nth(1).click()
 await expect(vocab.getByRole('region')).toHaveCount(1)
 await chips.nth(1).click()
 await expect(vocab.getByRole('region')).toHaveCount(0)
 const source=page.locator('[data-word-search-source]')
 const back=page.getByRole('link',{name:'Back Home',exact:true})
 const [v,s,b]=await Promise.all([vocab.boundingBox(),source.boundingBox(),back.boundingBox()])
 expect(s!.y).toBeGreaterThan(v!.y+v!.height)
 expect(b!.y).toBeGreaterThan(s!.y+s!.height)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:`test-results/word-search-cleanup-${width}.png`,fullPage:true})
})
