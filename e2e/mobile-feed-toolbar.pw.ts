import {test,expect} from '@playwright/test'
import {installYouTubeFixture} from './helpers/youtube'
const backend=`https://localhost:${process.env.AWM_TEST_BACKEND_PORT??4310}`
for(const width of [320,390,430,768])test(`mobile view and language toolbar ${width}`,async({page,request})=>{
 await request.post(`${backend}/fixture/spotlight`)
 await installYouTubeFixture(page)
 await page.addInitScript(()=>{if(!localStorage.getItem('awm-for-you-guest-playback-v1'))localStorage.setItem('awm-for-you-guest-playback-v1','123000')})
 await page.setViewportSize({width,height:900});await page.goto('/explore')
 const tools=page.locator('[data-mobile-view-tools]:visible'),toggle=tools.locator('[data-mobile-view-toggle]')
 const language=tools.getByRole('group',{name:'Source video language'})
 const ordinary=page.locator('[data-explore-player=active]:visible iframe')
 await expect(ordinary).toBeVisible();await expect(toggle).toHaveText('Explore')
 await expect(language.getByRole('button',{name:'AR',exact:true})).toHaveAttribute('aria-pressed','true')
 const original=await ordinary.getAttribute('srcdoc'),count=await page.evaluate(()=>(window as unknown as {__ytPlayers:unknown[]}).__ytPlayers.length)
 await language.getByRole('button',{name:'EN',exact:true}).click()
 await expect(ordinary).toHaveAttribute('srcdoc',original!)
 expect(await page.evaluate(()=>(window as unknown as {__ytPlayers:unknown[]}).__ytPlayers.length)).toBe(count)
 await expect(page.getByRole('button',{name:/Turn Explore sound on|Mute Explore video/})).not.toBeVisible()
 await toggle.click();await expect(page).toHaveURL(/view=foryou/)
 const source=page.locator('[data-for-you-source]')
 await expect(source.locator('iframe')).toBeVisible();await expect(toggle).toHaveText('For You')
 await expect.poll(async()=>Number((await source.getAttribute('data-for-you-source'))?.at(-1))).toBeGreaterThanOrEqual(4)
 await expect(page.getByRole('button',{name:/^Unmute clip$|^Mute clip$/})).not.toBeVisible()
 await expect(source.locator('iframe').contentFrame().getByRole('button',{name:'Volume',exact:true})).toBeVisible()
 const viewBox=(await toggle.boundingBox())!,langBox=(await language.boundingBox())!
 expect(Math.abs(viewBox.y-langBox.y)).toBeLessThan(3);expect(langBox.x).toBeGreaterThan(viewBox.x+viewBox.width)
 expect(langBox.x+langBox.width).toBeLessThanOrEqual(width)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.screenshot({path:`test-results/mobile-feed-toolbar-${width}.png`,fullPage:true})
 await toggle.click();await expect(ordinary).toBeVisible();await expect(toggle).toHaveText('Explore')
 await toggle.click();await expect(source.locator('iframe')).toBeVisible()
 await expect(language.getByRole('button',{name:'EN',exact:true})).toHaveAttribute('aria-pressed','true')
 await language.getByRole('button',{name:'AR',exact:true}).click()
 await expect.poll(async()=>Number((await source.getAttribute('data-for-you-source'))?.at(-1))).toBeLessThan(4)
 expect(await page.evaluate(()=>Number(localStorage.getItem('awm-for-you-guest-playback-v1')))).toBe(123000)
 await page.goBack();await expect(toggle).toHaveText('Explore');await expect(ordinary).toBeVisible()
 await page.goForward();await expect(toggle).toHaveText('For You');await expect(source.locator('iframe')).toBeVisible()
 const log=await(await request.get(`${backend}/fixture/request-log`)).json()
 expect(log.rpc.filter((name:string)=>name==='website_for_you_usage')).toHaveLength(0)
})
test('desktop retains existing view tabs, language and sound control',async({page,request})=>{
 await request.post(`${backend}/fixture/spotlight`);await installYouTubeFixture(page)
 await page.setViewportSize({width:1440,height:1000});await page.goto('/explore')
 await expect(page.locator('[data-mobile-view-tools]:visible')).toHaveCount(0)
 await expect(page.getByRole('button',{name:'For You feed',exact:true}).filter({visible:true})).toBeVisible()
 await expect(page.getByRole('button',{name:/Turn Explore sound on|Mute Explore video/})).toBeVisible()
 await page.getByRole('button',{name:'For You feed',exact:true}).filter({visible:true}).click()
 await expect(page.locator('[data-for-you-source] iframe')).toBeVisible()
 await expect(page.getByRole('button',{name:'Explore feed',exact:true}).filter({visible:true})).toBeVisible()
 await expect(page.getByRole('button',{name:'For You feed',exact:true}).filter({visible:true})).toBeVisible()
 await expect(page.getByRole('group',{name:'Source video language'}).filter({visible:true})).toBeVisible()
 await expect(page.getByRole('button',{name:/^Mute clip$|^Unmute clip$/})).toBeVisible()
 await expect(page.locator('[data-mobile-view-tools]:visible')).toHaveCount(0)
})
