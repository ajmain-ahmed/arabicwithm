async function signIn(context: BrowserContext, kind: 'free'|'premium'|'admin'|'editor') {
  const id = kind === 'free' ? '11111111-1111-4111-8111-111111111111' : kind === 'premium' ? '22222222-2222-4222-8222-222222222222' : kind === 'admin' ? '44444444-4444-4444-8444-444444444444' : '33333333-3333-4333-8333-333333333333'
  const expires = Math.floor(Date.now()/1000)+3600, encode = (value:unknown) => Buffer.from(JSON.stringify(value)).toString('base64url')
  const user = {id,aud:'authenticated',role:'authenticated',email:`${kind}@fixture.example`,created_at:'2026-01-01',app_metadata:{provider:'email'},user_metadata:{full_name:'Fixture learner'}}
  const access_token = `${encode({alg:'HS256',typ:'JWT'})}.${encode({sub:id,aud:'authenticated',exp:expires,role:'authenticated'})}.fixture-signature`
  await context.addCookies([{name:'sb-localhost-auth-token',value:`base64-${encode({access_token,refresh_token:'fixture-refresh',expires_at:expires,expires_in:3600,token_type:'bearer',user})}`,domain:'127.0.0.1',path:'/',sameSite:'Lax'}])
}
for (const kind of ['free','premium','admin','editor'] as const) test(`role-aware mobile side menu for ${kind}`,async({page,context})=>{
  await signIn(context,kind)
  await page.setViewportSize({width:390,height:844})
  await page.goto('/books')
  await expect(page.getByRole('button',{name:'Open user menu',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Open menu',exact:true}).click()
  const drawer = page.getByLabel('Site navigation')
  if(kind==='free'||kind==='premium') {
    await expect(drawer.locator('.mobile-list-btn')).toHaveText(['My Profile','Home','Explore','Watch','Read','Learn','Give Feedback','Support Us'])
    expect(await drawer.locator('[role=separator]').evaluateAll(nodes=>nodes.map(node=>node.previousElementSibling?.textContent))).toEqual(['My Profile','Learn'])
  } else {
    await expect(drawer.getByRole('button',{name:'Reviewer',exact:true})).toBeVisible()
    if(kind==='admin')await expect(drawer.getByRole('button',{name:'Admin',exact:true})).toBeVisible()
    for(const name of ['Memory','Grammar','Word Search'])await expect(drawer.getByRole('button',{name,exact:true})).toBeVisible()
  }
})
