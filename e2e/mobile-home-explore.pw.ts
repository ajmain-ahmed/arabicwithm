import { test, expect, type Page } from '@playwright/test'
import { installYouTubeFixture } from './helpers/youtube'
const backend = `https://localhost:${process.env.AWM_TEST_BACKEND_PORT ?? 4310}`
async function seek(page: Page, seconds: number) {
  await page.evaluate(time => (window as unknown as { __ytTime: (time: number) => void }).__ytTime(time), seconds)
}
for (const viewport of [{width:320,height:740},{width:390,height:844},{width:430,height:932},{width:844,height:390}]) {
  test(`mobile homepage and immersive feeds at ${viewport.width}x${viewport.height}`, async ({ page, request }) => {
    await page.setViewportSize(viewport)
    await installYouTubeFixture(page)
    await request.post(`${backend}/fixture/for-you-playback`)
    await page.goto('/')
    const actions = page.getByRole('navigation', {name:'Quick Actions',exact:true})
    await expect(actions).toBeVisible()
    expect(await actions.getByRole('link').allTextContents()).toEqual(['Memory','Grammar','Word Search','Explore'])
    const sections = await page.getByRole('heading',{level:2}).allTextContents()
    expect(sections.indexOf('Quick Actions')).toBeGreaterThan(sections.indexOf('Books'))
    await page.goto('/explore')
    const player = page.locator('[data-explore-player=active]')
    await expect(player).toBeVisible()
    const navHeight = await page.evaluate(() => parseFloat(getComputedStyle(document.documentElement).getPropertyValue('--awm-navbar-height')))
    const bounds = (await player.boundingBox())!
    expect(bounds.x).toBeCloseTo(0, 0)
    expect(bounds.y).toBeCloseTo(navHeight, 0)
    expect(bounds.width).toBeCloseTo(viewport.width, 0)
    expect(bounds.height).toBeCloseTo(viewport.height-navHeight, 0)
    const tabs = page.getByRole('group',{name:'Explore views'})
    const tabBounds = (await tabs.boundingBox())!
    expect(tabBounds.x+tabBounds.width/2).toBeCloseTo(viewport.width/2, 0)
    expect(tabBounds.y).toBeGreaterThanOrEqual(bounds.y)
    expect(tabBounds.y+tabBounds.height).toBeLessThan(bounds.y+bounds.height)
    const [explore, forYou] = await Promise.all([tabs.getByRole('button',{name:'Explore feed'}).boundingBox(), tabs.getByRole('button',{name:'For You feed'}).boundingBox()])
    expect(explore!.width).toBe(forYou!.width)
    expect(await tabs.evaluate(el => getComputedStyle(el).backgroundColor)).toBe('rgba(0, 0, 0, 0.3)')
    await expect(page.getByRole('note')).toHaveCount(0)
    await page.screenshot({path:`test-results/mobile-explore-${viewport.width}.png`})
    await tabs.getByRole('button',{name:'For You feed'}).click()
    const clip = page.locator('[data-for-you-source]')
    const clipPlayer = page.locator('[data-for-you-player]')
    const toolbar = page.locator('[data-mobile-for-you-toolbar]')
    const transcript = page.locator('[data-mobile-clip-transcript]')
    await expect(transcript.locator('[lang=en]')).toHaveText('Opening sentence')
    const videoBounds = (await clipPlayer.boundingBox())!, toolsBounds = (await toolbar.boundingBox())!
    expect(videoBounds.x).toBeCloseTo(0, 0)
    expect(videoBounds.y).toBeCloseTo(navHeight, 0)
    expect(videoBounds.width).toBeCloseTo(viewport.width, 0)
    expect(toolsBounds.y).toBeCloseTo(videoBounds.y+videoBounds.height, 0)
    expect(toolsBounds.height).toBeLessThan(65)
    expect(toolsBounds.y+toolsBounds.height).toBeLessThan(viewport.height)
    await expect(toolbar.getByRole('button',{name:'Settings',exact:true})).toBeVisible()
    await expect(page.getByRole('button',{name:'Next clip',exact:true})).toHaveCount(0)
    await expect(page.getByRole('button',{name:'Previous clip',exact:true})).toHaveCount(0)
    await expect(page.getByRole('note')).toHaveCount(0)
    expect(await transcript.locator('[data-clip-line] > p').evaluateAll(lines=>lines.map(line=>line.getAttribute('lang')))).toEqual(['ar','en'])
    await seek(page,510)
    await expect(transcript.locator('[lang=en]')).toHaveText('Later sentence')
    await expect(transcript).not.toContainText('Opening sentence')
    await seek(page,375)
    await expect(transcript).not.toContainText('Earlier sentence')
    await seek(page,522)
    await expect(page.getByRole('button',{name:'Replay clip',exact:true})).toHaveCount(0)
    await page.evaluate(() => {
      const player = (window as unknown as {__ytPlayers:{mute:()=>void}[]}).__ytPlayers.at(-1)!
      player.mute()
    })
    await seek(page,500)
    await expect(page.getByRole('button',{name:/Turn sound on|Play with sound/})).toHaveCount(0)
    const arabic = transcript.locator('[lang=ar]'), english = transcript.locator('[lang=en]')
    const sizes = await Promise.all([arabic.evaluate(el=>getComputedStyle(el).fontSize),english.evaluate(el=>getComputedStyle(el).fontSize)])
    await toolbar.getByRole('button',{name:'Settings',exact:true}).click()
    await page.getByRole('button',{name:'Increase Arabic text size',exact:true}).click()
    expect(await arabic.evaluate(el=>getComputedStyle(el).fontSize)).not.toBe(sizes[0])
    expect(await english.evaluate(el=>getComputedStyle(el).fontSize)).toBe(sizes[1])
    await page.getByRole('button',{name:'Done',exact:true}).click()
    const [arabicBounds, englishBounds, transcriptBounds] = await Promise.all([arabic.boundingBox(), english.boundingBox(), transcript.boundingBox()])
    expect(englishBounds!.y).toBeGreaterThanOrEqual(arabicBounds!.y+arabicBounds!.height)
    expect(englishBounds!.y+englishBounds!.height).toBeLessThanOrEqual(transcriptBounds!.y+transcriptBounds!.height)
    const original = await clip.getAttribute('data-for-you-source')
    await page.waitForTimeout(750)
    // Use native wheel input over the feed's navigation hint, outside inner scrolling.
    const hint = page.getByText('Scroll down for the next clip · scroll up to go back',{exact:true})
    await hint.hover()
    await page.mouse.wheel(0,120)
    await expect(clip).not.toHaveAttribute('data-for-you-source',original!)
    await page.waitForTimeout(750)
    const second = await clip.getAttribute('data-for-you-source')
    await transcript.dispatchEvent('wheel',{deltaY:-120})
    await expect(clip).toHaveAttribute('data-for-you-source',second!)
    await hint.hover()
    await page.mouse.wheel(0,-120)
    await expect(clip).toHaveAttribute('data-for-you-source',original!)
    await expect(clip.locator('iframe')).toHaveCount(1)
    expect(await page.evaluate(() => (window as unknown as {__ytPlayers:{playing:boolean;destroyed:boolean}[]}).__ytPlayers.filter(p=>p.playing&&!p.destroyed).length)).toBe(1)
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    await page.screenshot({path:`test-results/mobile-for-you-${viewport.width}.png`})
  })
}
test('desktop homepage and Explore controls retain their layout and hints',async({page,request})=>{
  await page.setViewportSize({width:1440,height:1000})
  await installYouTubeFixture(page)
  await request.post(`${backend}/fixture/for-you-playback`)
  await page.goto('/')
  await expect(page.getByRole('navigation',{name:'Quick Actions',exact:true})).toHaveCount(0)
  await page.goto('/explore')
  await expect(page.getByRole('note')).toBeVisible()
  await expect(page.getByRole('group',{name:'Explore views'})).toHaveCount(0)
  const normal = page.locator('[data-explore-player=active]')
  await expect(normal).toBeVisible()
  const bounds = (await normal.boundingBox())!
  expect(bounds.width).toBeLessThan(600)
  expect(bounds.height/bounds.width).toBeCloseTo(16/9,1)
  await page.getByRole('button',{name:'For You feed',exact:true}).click()
  await expect(page.getByRole('note')).toBeVisible()
  await expect(page.getByRole('button',{name:'Next clip',exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'Previous clip',exact:true})).toBeVisible()
  await expect(page.locator('[data-mobile-for-you-toolbar]')).toBeHidden()
  await expect(page.locator('[data-mobile-clip-transcript]')).toBeHidden()
  await expect(page.locator('[data-desktop-clip-transcript]')).toBeVisible()
  await expect(page.locator('[data-for-you-source] iframe')).toBeVisible()
  await seek(page,522)
  await expect(page.getByRole('button',{name:'Replay clip',exact:true})).toBeVisible()
  await page.screenshot({path:'test-results/desktop-explore-preserved.png'})
})
