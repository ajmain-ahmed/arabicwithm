import {test,expect} from '@playwright/test'
for(const width of [390,1440])test(`on-demand Learn initial workload and independent cards ${width}`,async({page})=>{
 const calls:string[]=[];page.on('request',r=>{if(/\/api\/learn\//.test(r.url()))calls.push(r.url())})
 await page.setViewportSize({width,height:844});await page.goto('/learn')
 const cards=page.locator('[data-practice-launcher]')
 await expect(cards).toHaveCount(3);await expect(page.getByRole('grid')).toHaveCount(0)
 expect(calls).toEqual([])
 await page.screenshot({path:`artifacts/learn-demand/${test.info().project.name}-${width}-initial.png`})
 const puzzle=page.locator('[data-practice-launcher=puzzle]'),grammar=page.locator('[data-practice-launcher=grammar]')
 await puzzle.getByRole('button',{name:'Start',exact:true}).dblclick()
 await expect(puzzle.getByRole('grid')).toBeVisible();expect(calls.filter(c=>c.includes('/puzzle'))).toHaveLength(1)
 const grid=await puzzle.getByRole('grid').textContent()
 await grammar.getByRole('button',{name:'Start',exact:true}).click()
 await expect(grammar.locator('[data-grammar-question]')).toBeVisible({timeout:30000})
 await grammar.getByRole('button',{name:'Close',exact:true}).click()
 await expect(grammar.getByRole('button',{name:'Start',exact:true})).toBeVisible()
 await expect(puzzle.getByRole('grid')).toHaveText(grid!)
 await page.screenshot({path:`artifacts/learn-demand/${test.info().project.name}-${width}-expanded.png`})
 for(const href of ['/grammar','/word-search','/memory'])await expect(page.locator(`[data-learn-navigation] a[href="${href}"]`)).toHaveCount(1)
 await page.reload();await expect(cards).toHaveCount(3);await expect(page.getByRole('grid')).toHaveCount(0)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 console.log('Initial Learn activity requests: 0; puzzle started once on demand.')
})
test('failed practice retries without resetting another activity',async({page})=>{
 await page.goto('/learn')
 const grammar=page.locator('[data-practice-launcher=grammar]'),puzzle=page.locator('[data-practice-launcher=puzzle]')
 await grammar.getByRole('button',{name:'Start',exact:true}).click()
 await expect(grammar.locator('[data-grammar-question]')).toBeVisible({timeout:30000})
 const question=await grammar.locator('[data-grammar-question]').getAttribute('data-grammar-question')
 await page.route('**/api/learn/puzzle**',route=>route.fulfill({status:503,json:{ok:false,error:'Temporary failure'}}))
 await puzzle.getByRole('button',{name:'Start',exact:true}).click()
 await expect(puzzle.getByRole('alert')).toBeVisible()
 await page.unroute('**/api/learn/puzzle**')
 await puzzle.getByRole('button',{name:'Retry',exact:true}).click()
 await expect(puzzle.getByRole('grid')).toBeVisible()
 await expect(grammar.locator('[data-grammar-question]')).toHaveAttribute('data-grammar-question',question!)
})
